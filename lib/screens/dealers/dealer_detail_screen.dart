/// A single dealer/vendor view: cost & contact details, the owning business,
/// the mirrored operating expense it generates, and a comment thread. Linked
/// entities resolve through the access-scoped [DataController].
class DealerDetailScreen extends StatelessWidget {
  const DealerDetailScreen({super.key, required this.dealerId});

  final String dealerId;

  @override
  Widget build(BuildContext context) {
    final data = context.watch<DataController>();
    final appState = context.watch<AppState>();
    final user = appState.currentUser;
    void back() => context.go(Routes.dealers);

    if (data.loading && !data.loaded) {
      return DetailPage.loading(
          title: 'Dealer', onBack: back, backLabel: 'Dealers');
    }

    final dealer = data.dealerById(dealerId);
    if (dealer == null) {
      return DetailPage.notFound(
        title: 'Dealer',
        onBack: back,
        backLabel: 'Dealers',
        message: 'This dealer may have been removed or is not accessible.',
      );
    }

    final t = context.tokens;
    final business = data.businessById(dealer.businessId);
    final currency = business?.currency ?? CurrencyCode.inr;
    String money(Money m) => MoneyFormatter.format(m, currency);
    // The mirrored expense (EXP-DLR-<dealerId>) generated by this dealer, if
    // it's visible in the current scope.
    final mirroredExpense = data.expenseById('EXP-DLR-${dealer.id}');
    final canEdit = user?.can(Permission.editDealer) ?? false;
    final canDelete = user?.can(Permission.deleteDealer) ?? false;
    final canViewExpense = user?.can(Permission.viewExpense) ?? false;
    final annual = dealer.costFrequency.isRecurring
        ? dealer.cost * dealer.costFrequency.occurrencesPerYear
        : dealer.cost;
    final repo = appState.repository;
    final hasUrl = dealer.url.trim().isNotEmpty;

    return DetailPage(
      title: dealer.name,
      subtitle: dealer.id,
      avatarName: dealer.name,
      status: StatusBadge.entity(dealer.status),
      backLabel: 'Dealers',
      onBack: back,
      meta: [
        if (business != null) DetailMeta(Icons.business_outlined, business.name),
        if (dealer.contactName.isNotEmpty)
          DetailMeta(Icons.person_outline, dealer.contactName,
              tooltip: 'Contact'),
        if (dealer.contactInfo.isNotEmpty)
          DetailMeta(Icons.contact_page_outlined, dealer.contactInfo,
              tooltip: 'Contact information'),
        if (hasUrl)
          DetailMeta(Icons.language, dealer.url,
              tooltip: 'Open website',
              onTap: () => DealerActions.openWebsite(dealer.url)),
      ],
      primaryAction: canEdit
          ? FilledButton.icon(
              onPressed: () =>
                  DealersScreen.openForm(context, dealer, dealer.businessId),
              icon: const Icon(Icons.edit_outlined, size: 18),
              label: const Text('Edit'),
            )
          : null,
      actions: [
        if (hasUrl)
          OutlinedButton.icon(
            onPressed: () => DealerActions.openWebsite(dealer.url),
            icon: const Icon(Icons.open_in_new, size: 18),
            label: const Text('Website'),
          ),
      ],
      menu: [
        if (canEdit && dealer.status != EntityStatus.inactive)
          DetailAction(
            label: 'Mark inactive',
            icon: Icons.pause_circle_outline,
            onSelected: () =>
                DealerActions.setStatus(context, dealer, EntityStatus.inactive),
          ),
        if (canEdit && dealer.status != EntityStatus.active)
          DetailAction(
            label: 'Mark active',
            icon: Icons.play_circle_outline,
            onSelected: () =>
                DealerActions.setStatus(context, dealer, EntityStatus.active),
          ),
        if (canDelete)
          DetailAction(
            label: 'Delete dealer',
            icon: Icons.delete_outline,
            destructive: true,
            onSelected: () async {
              if (await DealerActions.delete(context, dealer) &&
                  context.mounted) {
                back();
              }
            },
          ),
      ],
      kpis: [
        KpiItem(
          label: 'Cost',
          value: money(dealer.cost),
          icon: Icons.payments_outlined,
          caption: dealer.costFrequency.isRecurring
              ? dealer.costFrequency.label
              : 'One-time',
        ),
        KpiItem(
          label: 'Annualised',
          value: money(annual),
          icon: Icons.event_repeat_outlined,
          tooltip: 'Cost × occurrences per year (one-time counts once).',
        ),
        KpiItem(
          label: 'Monthly equivalent',
          value: money(annual / 12),
          icon: Icons.calendar_month_outlined,
        ),
        KpiItem(
          label: 'Since',
          value: dealer.startDate == null
              ? '—'
              : AppDate.format(dealer.startDate),
          icon: Icons.event_outlined,
          caption: dealer.endDate == null
              ? 'Ongoing'
              : 'Ends ${AppDate.format(dealer.endDate)}',
        ),
        KpiItem(
          label: 'Linked expense',
          value: mirroredExpense == null ? 'None' : mirroredExpense.status.label,
          icon: Icons.link,
          tone: mirroredExpense == null ? null : t.info,
          caption: mirroredExpense?.id,
          onTap: mirroredExpense != null && canViewExpense
              ? () => context
                  .go(Routes.expenseDetailPath(mirroredExpense.id))
              : null,
        ),
      ],
      activity: DetailActivityColumn(
        activityAt: dealer.lastActivityAt,
        comments: dealer.comments,
        canComment: canEdit,
        onPost: (comment) async {
          await repo.saveDealer(
            dealer.copyWith(comments: [...dealer.comments, comment]),
            isNew: false,
          );
        },
      ),
      children: [
        _DetailsCard(
          dealer: dealer,
          currency: currency,
          businessName: business?.name,
        ),
        if (mirroredExpense != null)
          _LinkedExpense(
            expense: mirroredExpense,
            currency: currency,
            canOpen: canViewExpense,
          ),
      ],
    );
  }
}

class _DetailsCard extends StatelessWidget {
  const _DetailsCard({
    required this.dealer,
    required this.currency,
    required this.businessName,
  });

  final Dealer dealer;
  final CurrencyCode currency;
  final String? businessName;

  @override
  Widget build(BuildContext context) {
    final t = context.tokens;
    final fields = <DetailField>[
      DetailField('Dealer ID', dealer.id, Icons.badge_outlined),
      DetailField('Business', businessName ?? '—', Icons.business_outlined),
      DetailField('Cost', MoneyFormatter.format(dealer.cost, currency),
          Icons.payments_outlined),
      DetailField('Frequency', dealer.costFrequency.label, Icons.repeat),
      DetailField('Contact Name', dealer.contactName, Icons.person_outline),
      DetailField(
          'Contact Info', dealer.contactInfo, Icons.contact_page_outlined),
      DetailField(
          'Start Date',
          dealer.startDate == null ? '—' : AppDate.format(dealer.startDate),
          Icons.event_outlined),
      DetailField(
          'End Date',
          dealer.endDate == null ? '—' : AppDate.format(dealer.endDate),
          Icons.event_available_outlined),
      DetailField('Dealer URL', dealer.url, Icons.link, isLink: true),
    ];

    Widget note(String title, String body) => Container(
          width: double.infinity,
          padding: const EdgeInsets.all(AppSpacing.md),
          decoration: BoxDecoration(
            color: t.surfaceAlt,
            borderRadius: BorderRadius.circular(AppSpacing.radiusSm),
          ),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Text(title,
                  style: TextStyle(
                      fontSize: 12,
                      fontWeight: FontWeight.w600,
                      color: t.textSecondary)),
              const SizedBox(height: 4),
              Text(body, style: const TextStyle(fontSize: 14, height: 1.4)),
            ],
          ),
        );

    return SectionCard(
      title: 'Dealer details',
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          DetailGrid(fields: fields),
          if (dealer.description.trim().isNotEmpty) ...[
            const SizedBox(height: AppSpacing.lg),
            note('Description', dealer.description),
          ],
          if (dealer.notes.trim().isNotEmpty) ...[
            const SizedBox(height: AppSpacing.md),
            note('Notes', dealer.notes),
          ],
        ],
      ),
    );
  }
}

/// The operating expense this dealer's cost is mirrored into.
class _LinkedExpense extends StatelessWidget {
  const _LinkedExpense({
    required this.expense,
    required this.currency,
    required this.canOpen,
  });

  final Expense expense;
  final CurrencyCode currency;
  final bool canOpen;

  @override
  Widget build(BuildContext context) {
    return AppDataGrid<Expense>(
      title: 'Linked Expense',
      subtitle: 'This dealer\'s cost is mirrored into Business Expenses',
      gridId: 'dealer.expense',
      rows: [expense],
      rowKey: (e) => e.id,
      showSearch: false,
      exportName: 'dealer-linked-expense',
      onRowTap: canOpen
          ? (e) => context.go(Routes.expenseDetailPath(e.id))
          : null,
      toolbarActions: [
        if (canOpen)
          TextButton.icon(
            onPressed: () =>
                context.go(Routes.expenseDetailPath(expense.id)),
            icon: const Icon(Icons.open_in_new, size: 16),
            label: const Text('View expense'),
          ),
      ],
      columns: [
        GridColumn<Expense>(
          id: 'name',
          label: 'Expense',
          pinned: true,
          flex: 2,
          cardRole: CardRole.title,
          cell: (e) => Text(e.name,
              maxLines: 1,
              overflow: TextOverflow.ellipsis,
              style: const TextStyle(fontWeight: FontWeight.w600)),
          sortValue: (e) => e.name.toLowerCase(),
          exportValue: (e) => e.name,
        ),
        GridColumn<Expense>(
          id: 'category',
          label: 'Category',
          cardRole: CardRole.meta,
          cell: (e) =>
              StatusBadge(label: e.category.label, tone: BadgeTone.neutral),
          sortValue: (e) => e.category.label,
          exportValue: (e) => e.category.label,
        ),
        GridColumn<Expense>(
          id: 'amount',
          label: 'Amount',
          numeric: true,
          cardRole: CardRole.metric,
          cell: (e) => CurrencyText(e.amount, currency: currency),
          sortValue: (e) => e.amount.minor,
          exportValue: (e) => e.amount.major.toStringAsFixed(2),
        ),
        GridColumn<Expense>(
          id: 'frequency',
          label: 'Frequency',
          cardRole: CardRole.meta,
          cell: (e) => Text(e.frequency.label),
          sortValue: (e) => e.frequency.label,
          exportValue: (e) => e.frequency.label,
        ),
        GridColumn<Expense>(
          id: 'status',
          label: 'Status',
          cardRole: CardRole.badge,
          cell: (e) => StatusBadge.entity(e.status),
          sortValue: (e) => e.status.label,
          exportValue: (e) => e.status.label,
        ),
      ],
    );
  }
}
